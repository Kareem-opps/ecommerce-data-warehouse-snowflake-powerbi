CREATE OR REPLACE VIEW ECOMMERCE_DB.ANALYTICS.v_aov AS
SELECT
    COUNT(DISTINCT order_id) AS total_orders,
    SUM(total_revenue) AS total_revenue,
    SUM(total_revenue) / COUNT(DISTINCT order_id) AS avg_order_value
FROM ECOMMERCE_DB.ANALYTICS.FACT_ORDER_ITEMS;
--===============================================================
--===============================================================
CREATE OR REPLACE VIEW ECOMMERCE_DB.ANALYTICS.v_cancellation_analysis AS
SELECT
    COUNT(DISTINCT order_id) AS canceled_orders,
    SUM(total_revenue) AS lost_revenue
FROM ECOMMERCE_DB.ANALYTICS.FACT_ORDER_ITEMS
WHERE order_status = 'canceled';
